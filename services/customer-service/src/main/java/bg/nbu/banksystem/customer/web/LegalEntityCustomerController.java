package bg.nbu.banksystem.customer.web;

import bg.nbu.banksystem.customer.application.LegalEntityCustomerService;
import bg.nbu.banksystem.customer.application.dto.AddressDto;
import bg.nbu.banksystem.customer.application.dto.CompanyNameUpdateDto;
import bg.nbu.banksystem.customer.application.dto.CustomerContactUpdateDto;
import bg.nbu.banksystem.customer.application.dto.EikCorrectionDto;
import bg.nbu.banksystem.customer.application.dto.LegalEntityCustomerRegistrationDto;
import bg.nbu.banksystem.customer.application.dto.LegalEntityCustomerViewDto;
import bg.nbu.banksystem.customer.application.dto.RepresentationEndDto;
import bg.nbu.banksystem.customer.application.dto.RepresentativeAdditionDto;
import bg.nbu.banksystem.customer.application.dto.RepresentativeCorrectionDto;
import bg.nbu.banksystem.customer.application.dto.RepresentativeViewDto;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.servlet.support.ServletUriComponentsBuilder;

import java.net.URI;
import java.util.UUID;

/**
 * REST API for legal-entity Customers and their Representatives.
 */
@RestController
@RequestMapping(value = "/api/customers/legal-entities", produces = MediaType.APPLICATION_JSON_VALUE)
@RequiredArgsConstructor
@ApiStandardResponses
@Tag(name = "Legal Entity Customer API",
        description = "Endpoints for registering and maintaining legal-entity customers and their representatives.")
public class LegalEntityCustomerController {

    static final String READ_ROLES = "hasAnyRole('CLERK', 'LOAN_OFFICER', 'ADMIN')";
    static final String WRITE_ROLES = "hasAnyRole('CLERK', 'ADMIN')";

    private final LegalEntityCustomerService legalEntityCustomerService;

    @Operation(operationId = "registerLegalEntityCustomer", summary = "Register a legal-entity customer",
            description = "The customer number is generated by the service. Representatives are added separately.")
    @ApiResponse(responseCode = "201", description = "Customer registered")
    @PostMapping(consumes = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<LegalEntityCustomerViewDto> registerLegalEntityCustomer(
            @Valid
            @RequestBody
            LegalEntityCustomerRegistrationDto registrationDto) {
        LegalEntityCustomerViewDto registered = legalEntityCustomerService.register(registrationDto);
        URI location = ServletUriComponentsBuilder.fromCurrentRequest().path("/{id}").buildAndExpand(registered.id())
                .toUri();

        return ResponseEntity.created(location).body(registered);
    }

    @Operation(operationId = "getLegalEntityCustomer", summary = "Get a legal-entity customer",
            description = "Includes current and ended representatives.")
    @ApiResponse(responseCode = "200", description = "Customer retrieved")
    @GetMapping("/{id}")
    @PreAuthorize(READ_ROLES)
    public ResponseEntity<LegalEntityCustomerViewDto> getLegalEntityCustomer(
            @Parameter(description = "Technical customer UUID")
            @PathVariable
            UUID id) {
        return ResponseEntity.ok(legalEntityCustomerService.getById(id));
    }

    @Operation(operationId = "updateLegalEntityCustomerCompanyName", summary = "Update the registered company name")
    @ApiResponse(responseCode = "200", description = "Company name updated")
    @PutMapping(value = "/{id}/company-name", consumes = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<LegalEntityCustomerViewDto> updateLegalEntityCustomerCompanyName(
            @PathVariable
            UUID id,
            @Valid
            @RequestBody
            CompanyNameUpdateDto companyNameUpdateDto) {
        return ResponseEntity.ok(legalEntityCustomerService.updateCompanyName(id, companyNameUpdateDto));
    }

    @Operation(operationId = "changeLegalEntityCustomerRegisteredAddress", summary = "Replace the registered address")
    @ApiResponse(responseCode = "200", description = "Address replaced")
    @PutMapping(value = "/{id}/registered-address", consumes = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<LegalEntityCustomerViewDto> changeLegalEntityCustomerRegisteredAddress(
            @PathVariable
            UUID id,
            @Valid
            @RequestBody
            AddressDto addressDto) {
        return ResponseEntity.ok(legalEntityCustomerService.changeRegisteredAddress(id, addressDto));
    }

    @Operation(operationId = "changeLegalEntityCustomerCorrespondenceAddress",
            summary = "Replace the correspondence address")
    @ApiResponse(responseCode = "200", description = "Address replaced")
    @PutMapping(value = "/{id}/correspondence-address", consumes = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<LegalEntityCustomerViewDto> changeLegalEntityCustomerCorrespondenceAddress(
            @PathVariable
            UUID id,
            @Valid
            @RequestBody
            AddressDto addressDto) {
        return ResponseEntity.ok(legalEntityCustomerService.changeCorrespondenceAddress(id, addressDto));
    }

    @Operation(operationId = "updateLegalEntityCustomerContact", summary = "Update the customer's email and phone")
    @ApiResponse(responseCode = "200", description = "Contact information updated")
    @PutMapping(value = "/{id}/contact", consumes = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<LegalEntityCustomerViewDto> updateLegalEntityCustomerContact(
            @PathVariable
            UUID id,
            @Valid
            @RequestBody
            CustomerContactUpdateDto contactUpdateDto) {
        return ResponseEntity.ok(legalEntityCustomerService.updateContactInformation(id, contactUpdateDto));
    }

    @Operation(operationId = "correctLegalEntityCustomerEik", summary = "Correct a wrongly entered EIK")
    @ApiResponse(responseCode = "200", description = "EIK corrected")
    @PutMapping(value = "/{id}/eik", consumes = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<LegalEntityCustomerViewDto> correctLegalEntityCustomerEik(
            @PathVariable
            UUID id,
            @Valid
            @RequestBody
            EikCorrectionDto eikCorrectionDto) {
        return ResponseEntity.ok(legalEntityCustomerService.correctEik(id, eikCorrectionDto));
    }

    @Operation(operationId = "closeLegalEntityCustomer", summary = "Close the customer relationship",
            description = "Representations are left unchanged.")
    @ApiResponse(responseCode = "200", description = "Customer closed")
    @PostMapping("/{id}/close")
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<LegalEntityCustomerViewDto> closeLegalEntityCustomer(
            @PathVariable
            UUID id) {
        return ResponseEntity.ok(legalEntityCustomerService.close(id));
    }

    @Operation(operationId = "reopenLegalEntityCustomer", summary = "Reopen a closed customer relationship")
    @ApiResponse(responseCode = "200", description = "Customer reopened")
    @PostMapping("/{id}/reopen")
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<LegalEntityCustomerViewDto> reopenLegalEntityCustomer(
            @PathVariable
            UUID id) {
        return ResponseEntity.ok(legalEntityCustomerService.reopen(id));
    }

    @Operation(operationId = "addRepresentative", summary = "Add a representative",
            description = "Supply either individualCustomerId, whose names are copied, or the names, but not both.")
    @ApiResponse(responseCode = "201", description = "Representative added")
    @PostMapping(value = "/{id}/representatives", consumes = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<RepresentativeViewDto> addRepresentative(
            @PathVariable
            UUID id,
            @Valid
            @RequestBody
            RepresentativeAdditionDto additionDto) {
        RepresentativeViewDto added = legalEntityCustomerService.addRepresentative(id, additionDto);

        URI location = ServletUriComponentsBuilder.fromCurrentRequest().path("/{representativeId}")
                .buildAndExpand(added.id()).toUri();

        return ResponseEntity.created(location).body(added);
    }

    @Operation(operationId = "getRepresentative", summary = "Get a representative")
    @ApiResponse(responseCode = "200", description = "Representative retrieved")
    @GetMapping("/{id}/representatives/{representativeId}")
    @PreAuthorize(READ_ROLES)
    public ResponseEntity<RepresentativeViewDto> getRepresentative(
            @PathVariable
            UUID id,
            @PathVariable
            UUID representativeId) {
        return ResponseEntity.ok(legalEntityCustomerService.getRepresentative(id, representativeId));
    }

    @Operation(operationId = "correctRepresentative", summary = "Correct a data-entry mistake in a representative",
            description = "Replaces every recorded value. A null validTo reopens a representation ended by mistake.")
    @ApiResponse(responseCode = "200", description = "Representative corrected")
    @PutMapping(value = "/{id}/representatives/{representativeId}", consumes = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<RepresentativeViewDto> correctRepresentative(
            @PathVariable
            UUID id,
            @PathVariable
            UUID representativeId,
            @Valid
            @RequestBody
            RepresentativeCorrectionDto correctionDto) {
        return ResponseEntity.ok(legalEntityCustomerService.correctRepresentative(id, representativeId, correctionDto));
    }

    @Operation(operationId = "endRepresentation", summary = "End a representative's authority")
    @ApiResponse(responseCode = "200", description = "Representation ended")
    @PostMapping(value = "/{id}/representatives/{representativeId}/end", consumes = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<RepresentativeViewDto> endRepresentation(
            @PathVariable
            UUID id,
            @PathVariable
            UUID representativeId,
            @Valid
            @RequestBody
            RepresentationEndDto endDto) {
        return ResponseEntity.ok(legalEntityCustomerService.endRepresentation(id, representativeId, endDto));
    }
}