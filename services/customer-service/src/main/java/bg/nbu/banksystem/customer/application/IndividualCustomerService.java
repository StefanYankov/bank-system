package bg.nbu.banksystem.customer.application;

import bg.nbu.banksystem.customer.application.dto.AddressDto;
import bg.nbu.banksystem.customer.application.dto.CustomerContactUpdateDto;
import bg.nbu.banksystem.customer.application.dto.EgnCorrectionDto;
import bg.nbu.banksystem.customer.application.dto.IndividualCustomerNameUpdateDto;
import bg.nbu.banksystem.customer.application.dto.IndividualCustomerRegistrationDto;
import bg.nbu.banksystem.customer.application.dto.IndividualCustomerViewDto;

import java.util.UUID;

/**
 * Application service for individual Customer use cases.
 */
public interface IndividualCustomerService {

    /**
     * Registers a new active individual Customer.
     *
     * <p>
     * The Customer number is generated by the service, not supplied by the caller.
     * </p>
     *
     * @param registrationDto registration data
     * @return the registered Customer
     * @throws bg.nbu.banksystem.starter.error.DomainException if the EGN is already registered
     */
    IndividualCustomerViewDto register(IndividualCustomerRegistrationDto registrationDto);

    /**
     * Retrieves an individual Customer.
     *
     * @param id Customer identifier
     * @return the Customer
     * @throws bg.nbu.banksystem.starter.error.DomainException if no individual Customer exists for the identifier
     */
    IndividualCustomerViewDto getById(UUID id);

    /**
     * Updates the Customer's name.
     *
     * @param id            Customer identifier
     * @param nameUpdateDto new name
     * @return the updated Customer
     * @throws bg.nbu.banksystem.starter.error.DomainException if the Customer does not exist or is closed
     */
    IndividualCustomerViewDto updateName(UUID id, IndividualCustomerNameUpdateDto nameUpdateDto);

    /**
     * Replaces the Customer's residential address.
     *
     * @param id         Customer identifier
     * @param addressDto new residential address
     * @return the updated Customer
     * @throws bg.nbu.banksystem.starter.error.DomainException if the Customer does not exist or is closed
     */
    IndividualCustomerViewDto changeResidentialAddress(UUID id, AddressDto addressDto);

    /**
     * Corrects an EGN entered incorrectly at registration.
     *
     * @param id               Customer identifier
     * @param egnCorrectionDto correct EGN
     * @return the updated Customer
     * @throws bg.nbu.banksystem.starter.error.DomainException if the Customer does not exist, is closed, or the EGN
     *                                                         belongs to another Customer
     */
    IndividualCustomerViewDto correctEgn(UUID id, EgnCorrectionDto egnCorrectionDto);

    /**
     * Updates the Customer's email and phone.
     *
     * @param id               Customer identifier
     * @param contactUpdateDto new contact information
     * @return the updated Customer
     * @throws bg.nbu.banksystem.starter.error.DomainException if the Customer does not exist or is closed
     */
    IndividualCustomerViewDto updateContactInformation(UUID id, CustomerContactUpdateDto contactUpdateDto);

    /**
     * Closes the Customer relationship.
     *
     * @param id Customer identifier
     * @return the closed Customer
     * @throws bg.nbu.banksystem.starter.error.DomainException if the Customer does not exist or is already closed
     */
    IndividualCustomerViewDto close(UUID id);

    /**
     * Reopens a closed Customer relationship.
     *
     * @param id Customer identifier
     * @return the reopened Customer
     * @throws bg.nbu.banksystem.starter.error.DomainException if the Customer does not exist or is already active
     */
    IndividualCustomerViewDto reopen(UUID id);
}
