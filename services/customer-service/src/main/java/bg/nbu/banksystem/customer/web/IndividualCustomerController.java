package bg.nbu.banksystem.customer.web;

import bg.nbu.banksystem.customer.application.IndividualCustomerService;
import bg.nbu.banksystem.customer.application.dto.AddressDto;
import bg.nbu.banksystem.customer.application.dto.CustomerContactUpdateDto;
import bg.nbu.banksystem.customer.application.dto.EgnCorrectionDto;
import bg.nbu.banksystem.customer.application.dto.IndividualCustomerNameUpdateDto;
import bg.nbu.banksystem.customer.application.dto.IndividualCustomerRegistrationDto;
import bg.nbu.banksystem.customer.application.dto.IndividualCustomerViewDto;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.servlet.support.ServletUriComponentsBuilder;

import java.net.URI;
import java.util.UUID;

/**
 * REST API for individual Customers.
 */
@RestController
@RequestMapping(value = "/api/customers/individuals", produces = MediaType.APPLICATION_JSON_VALUE)
@RequiredArgsConstructor
@ApiStandardResponses
@Tag(name = "Individual Customer API", description = "Endpoints for registering and maintaining individual customers.")
public class IndividualCustomerController {

    static final String READ_ROLES = "hasAnyRole('CLERK', 'LOAN_OFFICER', 'ADMIN')";
    static final String WRITE_ROLES = "hasAnyRole('CLERK', 'ADMIN')";

    private final IndividualCustomerService individualCustomerService;

    @Operation(operationId = "registerIndividualCustomer", summary = "Register an individual customer",
            description = "The customer number is generated by the service.")
    @ApiResponse(responseCode = "201", description = "Customer registered")
    @PostMapping(consumes = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<IndividualCustomerViewDto> registerIndividualCustomer(
            @Valid
            @RequestBody
            IndividualCustomerRegistrationDto registrationDto) {
        IndividualCustomerViewDto registered = individualCustomerService.register(registrationDto);

        URI location = ServletUriComponentsBuilder.fromCurrentRequest().path("/{id}").buildAndExpand(registered.id())
                .toUri();

        return ResponseEntity.created(location).body(registered);
    }

    @Operation(operationId = "getIndividualCustomer", summary = "Get an individual customer")
    @ApiResponse(responseCode = "200", description = "Customer retrieved")
    @GetMapping("/{id}")
    @PreAuthorize(READ_ROLES)
    public ResponseEntity<IndividualCustomerViewDto> getIndividualCustomer(
            @Parameter(description = "Technical customer UUID")
            @PathVariable
            UUID id) {
        return ResponseEntity.ok(individualCustomerService.getById(id));
    }

    @Operation(operationId = "updateIndividualCustomerName", summary = "Update the customer's name")
    @ApiResponse(responseCode = "200", description = "Name updated")
    @PutMapping(value = "/{id}/name", consumes = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<IndividualCustomerViewDto> updateIndividualCustomerName(
            @PathVariable
            UUID id,
            @Valid
            @RequestBody
            IndividualCustomerNameUpdateDto nameUpdateDto) {
        return ResponseEntity.ok(individualCustomerService.updateName(id, nameUpdateDto));
    }

    @Operation(operationId = "changeIndividualCustomerResidentialAddress",
            summary = "Replace the customer's residential address")
    @ApiResponse(responseCode = "200", description = "Address replaced")
    @PutMapping(value = "/{id}/residential-address", consumes = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<IndividualCustomerViewDto> changeIndividualCustomerResidentialAddress(
            @PathVariable
            UUID id,
            @Valid
            @RequestBody
            AddressDto addressDto) {
        return ResponseEntity.ok(individualCustomerService.changeResidentialAddress(id, addressDto));
    }

    @Operation(operationId = "updateIndividualCustomerContact", summary = "Update the customer's email and phone")
    @ApiResponse(responseCode = "200", description = "Contact information updated")
    @PutMapping(value = "/{id}/contact", consumes = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<IndividualCustomerViewDto> updateIndividualCustomerContact(
            @PathVariable
            UUID id,
            @Valid
            @RequestBody
            CustomerContactUpdateDto contactUpdateDto) {
        return ResponseEntity.ok(individualCustomerService.updateContactInformation(id, contactUpdateDto));
    }

    @Operation(operationId = "correctIndividualCustomerEgn", summary = "Correct a wrongly entered EGN")
    @ApiResponse(responseCode = "200", description = "EGN corrected")
    @PutMapping(value = "/{id}/egn", consumes = MediaType.APPLICATION_JSON_VALUE)
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<IndividualCustomerViewDto> correctIndividualCustomerEgn(
            @PathVariable
            UUID id,
            @Valid
            @RequestBody
            EgnCorrectionDto egnCorrectionDto) {
        return ResponseEntity.ok(individualCustomerService.correctEgn(id, egnCorrectionDto));
    }

    @Operation(operationId = "closeIndividualCustomer", summary = "Close the customer relationship")
    @ApiResponse(responseCode = "200", description = "Customer closed")
    @PostMapping("/{id}/close")
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<IndividualCustomerViewDto> closeIndividualCustomer(
            @PathVariable
            UUID id) {
        return ResponseEntity.ok(individualCustomerService.close(id));
    }

    @Operation(operationId = "reopenIndividualCustomer", summary = "Reopen a closed customer relationship")
    @ApiResponse(responseCode = "200", description = "Customer reopened")
    @PostMapping("/{id}/reopen")
    @PreAuthorize(WRITE_ROLES)
    public ResponseEntity<IndividualCustomerViewDto> reopenIndividualCustomer(
            @PathVariable
            UUID id) {
        return ResponseEntity.ok(individualCustomerService.reopen(id));
    }
}