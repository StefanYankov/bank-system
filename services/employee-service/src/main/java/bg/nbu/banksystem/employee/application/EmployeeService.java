package bg.nbu.banksystem.employee.application;

import bg.nbu.banksystem.employee.application.dto.EmployeeDisableDto;
import bg.nbu.banksystem.employee.application.dto.EmployeePositionChangeDto;
import bg.nbu.banksystem.employee.application.dto.EmployeeRegistrationDto;
import bg.nbu.banksystem.employee.application.dto.EmployeeUpdateDto;
import bg.nbu.banksystem.employee.application.dto.EmployeeViewDto;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;

import java.util.UUID;

/**
 * Application service for Employee Service use cases.
 *
 * <p>
 * Validates application input, coordinates persistence and domain operations,
 * and returns employee views. Entities never leave this boundary.
 * </p>
 */
public interface EmployeeService {

    /**
     * Registers a new active employee linked to an existing Keycloak identity.
     *
     * <p>
     * The employee number is generated by the service, not supplied by the caller.
     * </p>
     *
     * @param registrationDto employee registration data
     * @return the registered employee
     * @throws bg.nbu.banksystem.starter.error.DomainException if the Keycloak subject or work email is already linked to an employee
     */
    EmployeeViewDto register(EmployeeRegistrationDto registrationDto);

    /**
     * Retrieves an employee by technical identifier.
     *
     * @param id employee identifier
     * @return the employee
     * @throws bg.nbu.banksystem.starter.error.DomainException if no employee exists for the identifier
     */
    EmployeeViewDto getById(UUID id);

    /**
     * Retrieves an employee by business employee number.
     *
     * @param employeeNumber employee number, for example {@code EMP-000001}
     * @return the employee
     * @throws bg.nbu.banksystem.starter.error.DomainException if no employee exists for the employee number
     */
    EmployeeViewDto getByEmployeeNumber(String employeeNumber);

    /**
     * Retrieves the employee linked to the authenticated Keycloak subject.
     *
     * @param identitySubjectId authenticated Keycloak subject identifier
     * @return the current employee
     * @throws bg.nbu.banksystem.starter.error.DomainException if no employee is linked to the subject
     */
    EmployeeViewDto getCurrent(String identitySubjectId);

    /**
     * Retrieves a page of employees.
     *
     * @param pageable paging and sorting information
     * @return a page of employees
     */
    Page<EmployeeViewDto> getAll(Pageable pageable);

    /**
     * Replaces an employee's editable profile information.
     *
     * @param id        employee identifier
     * @param updateDto new profile information
     * @return the updated employee
     * @throws bg.nbu.banksystem.starter.error.DomainException if the employee does not exist or the work email is already used
     */
    EmployeeViewDto updateProfile(UUID id, EmployeeUpdateDto updateDto);

    /**
     * Changes an employee's position.
     *
     * @param id                employee identifier
     * @param positionChangeDto new position
     * @return the updated employee
     * @throws bg.nbu.banksystem.starter.error.DomainException if the employee does not exist
     */
    EmployeeViewDto changePosition(UUID id, EmployeePositionChangeDto positionChangeDto);

    /**
     * Disables an active employee from the supplied employment end date.
     *
     * @param id         employee identifier
     * @param disableDto final employment date
     * @return the disabled employee
     * @throws bg.nbu.banksystem.starter.error.DomainException if the employee does not exist or is already inactive
     */
    EmployeeViewDto disable(UUID id, EmployeeDisableDto disableDto);

    /**
     * Reactivates an inactive employee.
     *
     * @param id employee identifier
     * @return the reactivated employee
     * @throws bg.nbu.banksystem.starter.error.DomainException if the employee does not exist or is already active
     */
    EmployeeViewDto reactivate(UUID id);
}